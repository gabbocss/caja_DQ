-- Fase 5: contexto diario (festivos IT/Módena + clima), campañas y eventos.

CREATE TABLE IF NOT EXISTS contexto_dia (
  fecha DATE PRIMARY KEY,
  es_festivo BOOLEAN NOT NULL DEFAULT false,
  nombre_festivo TEXT,
  es_finde BOOLEAN NOT NULL DEFAULT false,
  dia_semana BIGINT NOT NULL DEFAULT 0,
  temp_media DOUBLE PRECISION,
  temp_min DOUBLE PRECISION,
  temp_max DOUBLE PRECISION,
  precipitacion_mm DOUBLE PRECISION,
  codigo_clima BIGINT,
  clima_resumen TEXT,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS campania (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'general'
    CHECK (tipo IN ('plato', 'evento', 'general')),
  canal TEXT NOT NULL DEFAULT '',
  producto_id BIGINT,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  notas TEXT NOT NULL DEFAULT '',
  activa BOOLEAN NOT NULL DEFAULT true,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fecha_fin >= fecha_inicio)
);

CREATE INDEX IF NOT EXISTS campania_fechas_idx
  ON campania (fecha_inicio, fecha_fin);

CREATE TABLE IF NOT EXISTS evento_restaurante (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'otro',
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  aforo_esperado BIGINT,
  notas TEXT NOT NULL DEFAULT '',
  activo BOOLEAN NOT NULL DEFAULT true,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fecha_fin >= fecha_inicio)
);

CREATE INDEX IF NOT EXISTS evento_restaurante_fechas_idx
  ON evento_restaurante (fecha_inicio, fecha_fin);

CREATE TABLE IF NOT EXISTS venta_campania (
  venta_id BIGINT NOT NULL REFERENCES venta (id) ON DELETE CASCADE,
  campania_id BIGINT NOT NULL REFERENCES campania (id) ON DELETE CASCADE,
  PRIMARY KEY (venta_id, campania_id)
);

CREATE TABLE IF NOT EXISTS venta_evento (
  venta_id BIGINT NOT NULL REFERENCES venta (id) ON DELETE CASCADE,
  evento_id BIGINT NOT NULL REFERENCES evento_restaurante (id) ON DELETE CASCADE,
  PRIMARY KEY (venta_id, evento_id)
);
