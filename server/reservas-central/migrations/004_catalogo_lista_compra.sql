-- Fase 4: productos (copia), lista de compra, supermercados y precios → PostgreSQL.
-- Import desde JSON preserva ids y flags hay_que_comprar / comprado.

CREATE TABLE IF NOT EXISTS supermercado (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  orden BIGINT NOT NULL DEFAULT 0,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS supermercado_orden_idx ON supermercado (orden);

CREATE TABLE IF NOT EXISTS lista_compra_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  cantidad TEXT NOT NULL DEFAULT '',
  hay_que_comprar BOOLEAN NOT NULL DEFAULT false,
  comprado BOOLEAN NOT NULL DEFAULT false,
  orden BIGINT NOT NULL DEFAULT 0,
  zona TEXT NOT NULL DEFAULT 'cocina'
    CHECK (zona IN ('cocina', 'sala')),
  supermercado_id BIGINT REFERENCES supermercado (id) ON DELETE SET NULL,
  url_metro TEXT NOT NULL DEFAULT '',
  url_cc TEXT NOT NULL DEFAULT '',
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS lista_compra_item_orden_idx
  ON lista_compra_item (orden);

CREATE INDEX IF NOT EXISTS lista_compra_item_hay_que_comprar_idx
  ON lista_compra_item (hay_que_comprar)
  WHERE hay_que_comprar = true;

CREATE INDEX IF NOT EXISTS lista_compra_item_supermercado_id_idx
  ON lista_compra_item (supermercado_id);

-- Copia de carta para el móvil (reemplazo completo desde la caja).
CREATE TABLE IF NOT EXISTS producto_copia (
  id BIGINT PRIMARY KEY,
  payload JSONB NOT NULL,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Legacy precios (GET/DELETE); POST ya no soportado en la app.
CREATE TABLE IF NOT EXISTS precio_lista_compra (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id BIGINT,
  supermercado_id BIGINT,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  fecha TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS precio_lista_compra_producto_id_idx
  ON precio_lista_compra (producto_id);

CREATE INDEX IF NOT EXISTS precio_lista_compra_supermercado_id_idx
  ON precio_lista_compra (supermercado_id);
