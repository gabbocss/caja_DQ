-- Fase 1: cliente por teléfono (opcional) y enlace en reserva.
-- Solo columnas NULLABLE / tablas nuevas: compatible con clientes API antiguos.

CREATE TABLE IF NOT EXISTS cliente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telefono TEXT NOT NULL,
  telefono_normalizado TEXT NOT NULL,
  nombre TEXT NOT NULL DEFAULT '',
  alergias_notas TEXT NOT NULL DEFAULT '',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  ultima_visita_en TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS cliente_telefono_normalizado_uidx
  ON cliente (telefono_normalizado);

CREATE INDEX IF NOT EXISTS cliente_actualizado_en_idx
  ON cliente (actualizado_en DESC);

ALTER TABLE reserva
  ADD COLUMN IF NOT EXISTS telefono TEXT,
  ADD COLUMN IF NOT EXISTS cliente_id BIGINT REFERENCES cliente (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS reserva_cliente_id_idx
  ON reserva (cliente_id);

CREATE INDEX IF NOT EXISTS reserva_telefono_idx
  ON reserva (telefono);
