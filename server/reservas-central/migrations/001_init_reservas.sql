-- Fase 0: esquema base de reservas en PostgreSQL.
-- Compatible con el JSON/API actual de programa_caja (camelCase en la API).

CREATE TABLE IF NOT EXISTS schema_migrations (
  id TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reserva (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_cliente TEXT NOT NULL,
  numero_personas BIGINT NOT NULL DEFAULT 1
    CHECK (numero_personas >= 0),
  fecha_hora_llegada TIMESTAMPTZ NOT NULL,
  alergias_notas TEXT NOT NULL DEFAULT '',
  estado TEXT NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'sentada', 'cancelada', 'cobrada')),
  mesa_asignada BIGINT,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS reserva_fecha_hora_llegada_idx
  ON reserva (fecha_hora_llegada);

CREATE INDEX IF NOT EXISTS reserva_estado_idx
  ON reserva (estado);

CREATE INDEX IF NOT EXISTS reserva_estado_llegada_idx
  ON reserva (estado, fecha_hora_llegada);

CREATE TABLE IF NOT EXISTS reserva_item (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  reserva_id BIGINT NOT NULL REFERENCES reserva (id) ON DELETE CASCADE,
  producto_id BIGINT NOT NULL,
  nombre_producto TEXT NOT NULL,
  cantidad BIGINT NOT NULL DEFAULT 1 CHECK (cantidad > 0),
  precio_unitario NUMERIC(12, 2) NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS reserva_item_reserva_id_idx
  ON reserva_item (reserva_id);
